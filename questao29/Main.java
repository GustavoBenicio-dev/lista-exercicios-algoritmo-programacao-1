public class Main {
    public static void main(String[] args) {
        double alturaPessoa1 = 1.80, alturaPessoa2 = 1.65;

        System.out.println("Igual: " + (alturaPessoa1 == alturaPessoa2));
        System.out.println("Diferente: " + (alturaPessoa1 != alturaPessoa2));
        System.out.println("Maior: " + (alturaPessoa1 > alturaPessoa2));
        System.out.println("Menor: " + (alturaPessoa1 < alturaPessoa2));
        System.out.println("Maior ou igual: " + (alturaPessoa1 >= alturaPessoa2));
        System.out.println("Menor ou igual: " + (alturaPessoa1 <= alturaPessoa2));
    }
}