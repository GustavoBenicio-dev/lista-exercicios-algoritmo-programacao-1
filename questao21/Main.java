public class Main {
    public static void main(String[] args) {
        int a = 10, b = 20;

        System.out.println("Igual: " + (a == b));
        System.out.println("Diferente: " + (a != b));
        System.out.println("Maior: " + (a > b));
        System.out.println("Menor: " + (a < b));
    }
}