public class Main {
    public static void main(String[] args) {
        int n1 = 8, n2 = 12;

        System.out.println("n1 == n2: " + (n1 == n2));
        System.out.println("n1 != n2: " + (n1 != n2));
        System.out.println("n1 > n2: " + (n1 > n2));
        System.out.println("n1 < n2: " + (n1 < n2));
        System.out.println("n1 >= n2: " + (n1 >= n2));
        System.out.println("n1 <= n2: " + (n1 <= n2));
    }
}